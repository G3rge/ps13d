int ps1_font_text_width(const char* text) {
    int n = 0;
    while (*text) { n++; text++; }
    return n * PS1_FONT_STEP;
}

void ps1_font_draw(Ps1Framebuffer* fb, int x, int y, rgb555_t color,
                   const char* text) {
    u16* dst = fb->px;
    while (*text) {
        char c = *text;
        const u8* g;
        int r, cc;
        if (c >= 'a' && c <= 'z') c = (char)(c - ('a' - 'A'));
        if (c < ' ') c = ' ';
        if (c > '_') c = ' ';
        g = FONT_DATA[(u8)c - ' '];
        for (r = 0; r < PS1_FONT_ROWS; r++) {
            u8 row = g[r];
            int py = y + r;
            if (py < 0 || py >= PS1_SCREEN_H) continue;
            for (cc = 0; cc < PS1_FONT_W; cc++) {
                int px = x + cc;
                if (px < 0 || px >= PS1_SCREEN_W) continue;
                if (row & (1u << (4 - cc)))
                    dst[py * PS1_SCREEN_W + px] = color;
            }
        }
        x += PS1_FONT_STEP;
        text++;
    }
}